async function sheet() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Doctors");
  ws.columns = [
    { header: "Name", key: "name", width: 26 },
    { header: "Email", key: "email", width: 36 },
    { header: "Specialty", key: "specialty", width: 22 },
    { header: "City", key: "city", width: 18 },
    { header: "Hospital", key: "hospital", width: 32 },
  ];
  ws.getRow(1).font = { bold: true };
  for (const [name, specialty, city, hospital] of doctors) {
    const email = `${name.toLowerCase().replace(/\s+/g, ".")}@example.com`;
    ws.addRow({ name: `Dr. ${name}`, email, specialty, city, hospital });
  }
  await wb.xlsx.writeFile(path.join(out, "doctors-sample.xlsx"));
}

/** Builds a tiny, valid one-page PDF by hand (no dependencies). */
function pdf() {
  const lines: [number, number, string][] = [
    [22, 760, "Sample Article for the Dispatch demo"],
    [12, 732, "Clinical Update  |  Reproductive Medicine  |  Demo content"],
    [11, 690, "This PDF is a placeholder used to demonstrate scheduled article emails."],
    [11, 672, "In real use, upload the article you downloaded from the publisher's website."],
    [14, 630, "Summary"],
    [11, 606, "Each doctor on the list receives an individual email with this PDF attached."],
    [11, 588, "The send can be scheduled once, daily or weekly, and every delivery is tracked."],
    [11, 570, "Failed deliveries can be retried from the Activity page."],
    [14, 528, "Key points"],
    [11, 504, "1. Upload the doctors list once as an Excel sheet; re-upload it to update."],
    [11, 486, "2. Attach the article PDF and choose the schedule."],
    [11, 468, "3. Send yourself a test, then let the schedule take over."],
    [9, 60, "Generated by scripts/make-samples.ts"],
  ];
  const esc = (s: string) => s.replace(/[\\()]/g, (c) => `\\${c}`);
  const stream = lines.map(([size, y, text]) => `BT /F1 ${size} Tf 64 ${y} Td (${esc(text)}) Tj ET`).join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
  ];
  let body = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(body));
    body += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(body);
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  body += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  fs.writeFileSync(path.join(out, "sample-article.pdf"), body);
}

