import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { env } from "@/lib/env";

export const MAX_PDF_BYTES = 25 * 1024 * 1024;

export async function savePdf(file: File): Promise<{ path: string; name: string; size: number }> {
  const buf = Buffer.from(await file.arrayBuffer());
  if (buf.subarray(0, 5).toString() !== "%PDF-") throw new Error("That file doesn't look like a PDF.");
  if (buf.length > MAX_PDF_BYTES) throw new Error("PDF is larger than 25 MB.");
  await fs.mkdir(env.pdfDir, { recursive: true });
  const stored = `${Date.now()}-${crypto.randomBytes(4).toString("hex")}.pdf`;
  await fs.writeFile(path.join(env.pdfDir, stored), buf);
  return { path: stored, name: safeName(file.name), size: buf.length };
}

export function readPdf(stored: string): Promise<Buffer> {
  return fs.readFile(resolve(stored));
}

export async function deletePdf(stored: string) {
  await fs.rm(resolve(stored), { force: true });
}

function resolve(stored: string) {
  // Stored names are generated by us; basename() guards against path tricks anyway.
  return path.join(env.pdfDir, path.basename(stored));
}

function safeName(name: string) {
  const base = path.basename(name || "article.pdf").replace(/[^\w.\- ()]+/g, "_");
  return base.toLowerCase().endsWith(".pdf") ? base : `${base}.pdf`;
}

export function formatBytes(bytes: number) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
